import assert from 'node:assert/strict';
import express from 'express';
import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
import { makeContinuationFixture } from './helpers/continuation-save-fixture.mjs';

const app = express();
app.get('/', (_req, res) => res.type('html').send('<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="/css/tokens.css"><style>body{background:#10151b;color:#eee;margin:0}timeline-navigator{width:300px;height:850px}</style><main id="app"></main>'));
app.use(express.static(process.cwd()));
const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.evaluate(async fixture => {
    await import('/js/ui/timeline-navigator.js'); await import('/js/ui/settings-panel.js');
    const { stateManager: sm } = await import('/js/core/state-manager.js');
    const { timelineSystem: timeline } = await import('/js/systems/timeline-system.js');
    const { eventBus } = await import('/js/core/event-bus.js');
    const { compressTimelineNode } = await import('/js/core/timeline-node-codec.js');
    const { NarutoRPGApp } = await import('/js/app.js');
    const { appShell } = await import('/js/ui/app-shell.js');
    for (let i = 0; i < fixture.nodes.length - 20; i++) fixture.nodes[i] = await compressTimelineNode(fixture.nodes[i]);
    await sm.initDB(); await sm.dbReplaceTimeline(fixture);
    sm.restore(fixture.nodes.at(-1).state_snapshot);
    sm.state._ui.settings.autoArchive = false;
    Object.assign(window, { sm, timeline, eventBus });
    window.fullReads = 0;
    const getAll = IDBObjectStore.prototype.getAll;
    IDBObjectStore.prototype.getAll = function(...args) { if (this.name === 'timeline_nodes') fullReads++; return getAll.apply(this, args); };
    appShell.init(document.querySelector('#app')); await timeline.init();
    const app = new NarutoRPGApp();
    app.pipeline = { isProcessing: false, setHistory: history => { window.aiHistory = history; }, clearHistory: () => {} };
    app._bindEvents();
    window.openSettings = () => { const panel = document.createElement('settings-panel'); panel.setAttribute('section', 'gameplay'); document.body.append(panel); };
  }, makeContinuationFixture(260));
  const nav = page.locator('timeline-navigator');
  const mainNodes = () => nav.locator('.history-pager[data-branch="branch_main"] + .list .node');
  await page.waitForFunction(() => document.querySelector('timeline-navigator').shadowRoot.querySelectorAll('.node').length === 200, null, { timeout: 5000 }).catch(async error => {
    console.log({ errors, state: await page.evaluate(() => { const nav = document.querySelector('timeline-navigator'); return { nodes: nav._nodes.length, branches: nav._branches.length, count: nav.shadowRoot.querySelectorAll('.node').length, text: nav.shadowRoot.textContent.slice(-600) }; }) });
    throw error;
  });
  assert.equal(await mainNodes().count(), 100);
  await nav.locator('[data-branch="branch_main"][data-history-page="1"]').click();
  assert.equal(await mainNodes().first().getAttribute('data-id'), 'main_61');
  await nav.locator('[data-branch="branch_main"][data-history-page="2"]').click();
  assert.equal(await mainNodes().count(), 60);
  assert.equal(await page.evaluate(() => sm.getSub('_meta').current_node_id), 'if_260', 'paging does not change the play position');
  await nav.locator('.node-toggle[data-id="main_1"]').click();
  await page.waitForFunction(() => window.aiHistory?.some(message => message.content?.includes('主线1')));
  assert.equal(await page.evaluate(() => sm.getSub('_meta').current_node_id), 'main_1');
  assert.ok(await page.locator('#app').innerText().then(text => text.includes('主线1')));
  assert.equal(await page.evaluate(() => aiHistory.some(message => message.content?.includes('IF260'))), false);
  await nav.locator('.node-toggle[data-id="if_260"]').click();
  await page.waitForFunction(() => window.aiHistory?.some(message => message.content?.includes('IF260')));
  const beforeSettings = await page.evaluate(() => JSON.stringify(aiHistory));
  await page.evaluate(() => openSettings());
  const settings = page.locator('settings-panel');
  const countInput = settings.getByRole('spinbutton', { name: '每页历史回合数' });
  assert.equal(await countInput.inputValue(), '100');
  await countInput.fill('37'); await countInput.blur();
  await settings.locator('.actions > [data-action="save"]').click();
  await page.waitForFunction(() => sm.getSub('_ui').settings.historyViewTurns === 37);
  await page.waitForFunction(() => document.querySelector('timeline-navigator').shadowRoot.querySelectorAll('.history-pager[data-branch="branch_main"] + .list .node').length === 37);
  assert.equal(await mainNodes().count(), 37);
  await countInput.fill('0'); await countInput.blur();
  await settings.locator('.actions > [data-action="save"]').click();
  assert.equal(await page.evaluate(() => sm.getSub('_ui').settings.historyViewTurns), 37);
  await countInput.fill('300'); await countInput.blur();
  await settings.locator('.actions > [data-action="save"]').click();
  await page.waitForFunction(() => sm.getSub('_ui').settings.historyViewTurns === 300);
  await page.waitForFunction(() => document.querySelector('timeline-navigator').shadowRoot.querySelectorAll('.history-pager[data-branch="branch_main"] + .list .node').length === 260);
  assert.equal(await mainNodes().count(), 260, 'custom values above 200 are not silently capped');
  assert.equal(await page.evaluate(() => JSON.stringify(aiHistory)), beforeSettings, 'display size must not expand model context');
  await page.evaluate(async () => { const node = await timeline._hydrateNode(await sm.dbGet('timeline_nodes', 'main_10')); sm.restore(node.state_snapshot); });
  assert.equal(await page.evaluate(() => sm.getSub('_ui').settings.historyViewTurns), 300);
  await mkdir('reports/history-window', { recursive: true });
  for (const width of [320, 390, 768]) {
    await page.setViewportSize({ width, height: 900 });
    await countInput.scrollIntoViewIfNeeded();
    const box = await countInput.boundingBox();
    assert.ok(box.x >= 0 && box.x + box.width <= width + 1, `${width}px setting overflow`);
  }
  await page.setViewportSize({ width: 390, height: 900 });
  await page.screenshot({ path: 'reports/history-window/settings-mobile.png' });
  assert.equal(await page.evaluate(() => fullReads), 0);
  await page.reload();
  const restored = await page.evaluate(async () => {
    const { stateManager: sm } = await import('/js/core/state-manager.js');
    await sm.initDB(); await sm.loadUIPrefs();
    const tx = sm._db.transaction('timeline_nodes'), count = tx.objectStore('timeline_nodes').count();
    const nodes = await new Promise(resolve => tx.oncomplete = () => resolve(count.result));
    return { size: sm.getSub('_ui').settings.historyViewTurns, nodes };
  });
  assert.deepEqual(restored, { size: 300, nodes: 390 });
  assert.deepEqual(errors, []);
  console.log('PASS default 100, custom 37/300, older-page compressed narrative, paging preserves play position, browsing preserves future nodes, invalid input, refresh/rollback preferences, mobile layout, zero full-node reads');
} finally { await browser?.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
