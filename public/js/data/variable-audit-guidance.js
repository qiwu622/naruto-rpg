export function buildVariableTimeAnchor(state = {}, compactState = {}) {
  const calendar = state?.['世界·时间'] ?? state?.world_state?.calendar
    ?? state?.world?.['世界·时间'] ?? compactState?.world?.['世界·时间']
    ?? compactState?.world_state?.calendar ?? compactState?.['世界·时间'];
  const value = typeof calendar === 'string' && calendar.trim() ? calendar : null;
  return '[本回合时间基点]\n' + JSON.stringify({
    current_calendar: value,
    parsed_calendar: parseGameCalendar(value),
    days_per_month: GAME_DAYS_PER_MONTH,
    write_path: 'world_state.calendar'
  }) + '\n这是只读的已记录时间；用它和最终正文核对落点，不是每回合必须保持不变的目标。未知日期不使用预设示例或默认开局日期填补。';
}
